from pathlib import Path
import argparse
import hashlib
import importlib
import json
import sys
import traceback
import torch
from calflops import calculate_flops

PAPER = Path('/home/wuxi/Dent-FINE-paper')
PROJECT = Path('/home/wuxi/Dent-FINE')
OUT = Path(__file__).resolve().parent / 'complexity_records'


def digest(p):
    h = hashlib.sha256()
    with Path(p).open('rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''):
            h.update(b)
    return h.hexdigest()


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--family', choices=['yolov8s','yolo11s','rtdetr_l','caf_yolo_s','deim_s','rtdetrv2_s','faster_rcnn','dome_detr_s','dent_stride_pano','dent_stride_mobile','dent_stride_dslr'], required=True)
    a=parser.parse_args()
    torch.set_num_threads(4)
    torch.manual_seed(0)
    OUT.mkdir(exist_ok=True)
    result=[]
    if a.family == 'caf_yolo_s':
        sys.path.insert(0,str(PROJECT/'third_party/CAF-YOLO'))
    elif a.family in ['deim_s','rtdetrv2_s']:
        base=PAPER/'materials/official_baselines_2026-09-10'
        sys.path.insert(0,str(base/'upstream'/('DEIM' if a.family=='deim_s' else 'RT-DETR/rtdetrv2_pytorch')))
        core=importlib.import_module(('engine' if a.family=='deim_s' else 'src')+'.core')
    elif a.family=='dome_detr_s':
        sys.path.insert(0,str(PROJECT/'third_party/dome_detr'))
        core=importlib.import_module('src.core')
    elif a.family=='faster_rcnn':
        sys.path.insert(0,'/home/wuxi/detectron2')
    elif a.family.startswith('dent_stride_'):
        base=PAPER/'materials/cmig_selected_configs_multiseed_2026-10-11'
        sys.path.insert(0,str(base/'source_snapshots'/('mobile' if a.family.endswith('mobile') else 'local')))
        core=importlib.import_module('engine.core')
    cohorts=({'dent_stride_pano':['dentex'],'dent_stride_mobile':['phone'],'dent_stride_dslr':['dslr']}.get(a.family,['dentex','phone','dslr']))
    for c in cohorts:
        model=None
        rec={'family':a.family,'cohort':c,'input':[1,3,640,640],'precision':'FP32',
             'device':'CPU','tool':'calflops','tool_version':'0.3.2',
             'forward_form':'native, unfused, evaluation mode',
             'scope':'model forward, not data loading or postprocessing; unsupported operations excluded',
             'input_values':'explicit all-zero FP32 tensor; no uninitialized calflops autogenerated input'}
        try:
            if a.family.startswith('dent_stride_'):
                configuration,seed={'dent_stride_pano':('pano_spatialshape_original',3),
                    'dent_stride_mobile':('mobile_proto_k4_tau0p50',2),
                    'dent_stride_dslr':('dslr_cmfa_extra_decay_only',3)}[a.family]
                cfgpath=base/'configs'/configuration/f'seed_{seed}.yml'
                cfg=core.YAMLConfig(str(cfgpath))
                cfg.yaml_cfg['HGNetv2']['pretrained']=False
                model=cfg.model
                weight=base/'runs'/configuration/f'seed_{seed}/best.pth'
                payload=torch.load(weight,map_location='cpu',weights_only=False)
                state=payload['ema']['module'] if isinstance(payload.get('ema'),dict) else payload['model']
                model.load_state_dict(state,strict=True)
                summary=json.loads((weight.parent/'native_coco_metrics.json').read_text())
                expected=summary['params_total']
                if a.family.endswith('mobile'):rec['input']=[1,3,1024,1024]
                rec.update(source_config=str(cfgpath),config_sha256=digest(cfgpath),
                           checkpoint=str(weight),checkpoint_sha256=digest(weight))
            elif a.family in ['deim_s','rtdetrv2_s']:
                cfgpath=base/'configs'/f'{a.family}_{c}.yml'
                key='HGNetv2' if a.family=='deim_s' else 'PResNet'
                cfg=core.YAMLConfig(str(cfgpath),**{key:{'pretrained':False}})
                model=cfg.model
                rec.update(source_config=str(cfgpath),config_sha256=digest(cfgpath),
                           initialization='No checkpoint needed for this fixed-operation architecture profile')
                summary=json.loads((base/'runs'/a.family/c/'seed_0/metrics_summary.json').read_text())
                expected=summary['params_training_total']
            elif a.family in ['faster_rcnn','dome_detr_s']:
                if c=='dslr':
                    suffix='faster_rcnn_r50_fpn_fdi52' if a.family=='faster_rcnn' else 'dome_detr_s_fdi52'
                    run=PROJECT/'outputs/viewnet3_dslr_baseline_comparison/runs'/suffix
                else:
                    suffix='faster_rcnn' if a.family=='faster_rcnn' else 'dome_detr_s_tuned301'
                    run=PROJECT/'outputs/cross_dataset_baseline_comparison'/c/'runs'/suffix
                meta=json.loads((run/'coco_eval/coco_metrics.json').read_text())
                expected=meta['num_parameters']
                if a.family=='faster_rcnn':
                    from detectron2.config import get_cfg
                    from detectron2.modeling import build_model
                    from detectron2.checkpoint import DetectionCheckpointer
                    cfgpath=run/'config.yaml'
                    cfg=get_cfg();cfg.merge_from_file(str(cfgpath));cfg.MODEL.DEVICE='cpu'
                    detector=build_model(cfg).eval()
                    weight=Path(meta['weights'])
                    DetectionCheckpointer(detector).load(str(weight))
                    class DetectorForward(torch.nn.Module):
                        def __init__(self,detector):
                            super().__init__();self.detector=detector
                        def forward(self,x):
                            data=[{'image':im,'height':640,'width':640}for im in x]
                            return self.detector.inference(data,do_postprocess=False)
                    model=DetectorForward(detector)
                    rec.update(proposals_topk=int(cfg.MODEL.RPN.POST_NMS_TOPK_TEST),
                               internal_proposal_and_NMS_operations='Native internal inference retained; final pixel-space postprocessing disabled.')
                else:
                    cfgpath=Path(meta['config'])
                    updates=core.yaml_utils.parse_cli(meta.get('updates',[]))
                    cfg=core.YAMLConfig(str(cfgpath),**updates)
                    cfg.yaml_cfg['HGNetv2']['pretrained']=False
                    model=cfg.model
                    weight=Path(meta['checkpoint'])
                    payload=torch.load(weight,map_location='cpu',weights_only=False)
                    state=payload['ema']['module'] if isinstance(payload.get('ema'),dict) else payload['model']
                    model.load_state_dict(state,strict=True)
                    rec['density_adaptive_queries']=True
                    rec['effective_config_updates']=meta.get('updates',[])
                rec.update(source_config=str(cfgpath),config_sha256=digest(cfgpath),
                           checkpoint=str(weight),checkpoint_sha256=digest(weight))
            else:
                if c=='dslr' and a.family!='rtdetr_l':
                    suffix={'yolov8s':'yolov8s_fdi52_no_flip','yolo11s':'yolo11s_fdi52_no_flip','caf_yolo_s':'caf_yolo_s_fdi52'}[a.family]
                    weight=PROJECT/'outputs/viewnet3_dslr_baseline_comparison/runs'/suffix/'weights/best.pt'
                else:
                    weight=PROJECT/'outputs/cross_dataset_baseline_comparison'/c/'runs'/a.family/'weights/best.pt'
                checkpoint=torch.load(weight,map_location='cpu',weights_only=False)
                model=checkpoint.get('ema')
                if model is None:model=checkpoint['model']
                rec.update(checkpoint=str(weight),checkpoint_sha256=digest(weight))
                del checkpoint
                expected=None
            model=model.cpu().float().eval()
            params=sum(p.numel()for p in model.parameters())
            if expected is not None:
                assert params==expected,(params,expected)
            sample=torch.zeros(*rec['input'],dtype=torch.float32)
            query_counts=[]
            hook=None
            if a.family=='dome_detr_s':
                def capture_queries(module,args,output):
                    query_counts.append(int(output['pred_logits'].shape[1]))
                hook=model.register_forward_hook(capture_queries)
            flops,macs,_=calculate_flops(model=model,args=[sample],
                output_as_string=False,print_detailed=False,print_results=False)
            if hook is not None:hook.remove()
            rec.update(params_native_total=params,Params_M=params/1e6,
                       GFLOPs=float(flops)/1e9,GMACs=float(macs)/1e9,status='measured')
            if a.family=='dome_detr_s':
                rec['profile_query_count']=query_counts[-1]
                rec['query_counts_during_profile']=query_counts
                rec['dynamic_compute_note']='Count is for this stated zero-image input; query count and compute may vary with images.'
        except Exception as e:
            rec.update(status='unavailable',error=f'{type(e).__name__}: {e}')
        result.append(rec)
        print(json.dumps({k:v for k,v in rec.items() if k in ['family','cohort','Params_M','GFLOPs','GMACs','status','error']}),flush=True)
        if model is not None:del model
    (OUT/(a.family+'.json')).write_text(json.dumps(result,indent=2,ensure_ascii=False))


if __name__=='__main__':main()
